import { Moon, Sun } from 'lucide-react'

import { useTheme } from '../hooks/useTheme'

export function ThemeToggle() {
  const { theme, toggleTheme } = useTheme()
  const isDark = theme === 'dark'

  return (
    <button
      type="button"
      onClick={toggleTheme}
      aria-label={isDark ? 'Activer le mode clair' : 'Activer le mode sombre'}
      title={isDark ? 'Mode clair' : 'Mode sombre'}
      className="border-[var(--border-subtle)] bg-[var(--surface-raised)] text-muted hover:text-brand-700 dark:hover:text-brand-300 inline-flex h-10 w-10 items-center justify-center rounded-lg border transition-colors"
    >
      {isDark ? <Sun className="h-[18px] w-[18px]" /> : <Moon className="h-[18px] w-[18px]" />}
    </button>
  )
}